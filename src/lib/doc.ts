import { DOC_TYPE } from "./data";

export interface DocumentContent {
  recipientTitle: string;
  recipientSub: string;
  plaintiffLabel: string;
  defendantLabel: string;
  subject: string;
  body: string;
  tableTitle: string;
  articles: string[];
  finalRequest: string;
  signatureLabel: string;
}

interface DocContentInput {
  docType: string;
  name: string;
  employer: string;
  yearsFa: string;
  salaryFa: string;
  contract: string;
  hasDetailed: boolean;
  claimsList: string;
  totalFa: string;
  hasClaims: boolean;
  dismissalDate?: string | null;
  insurancePeriod?: string | null;
  noticeDeadlineDays?: string | null;
}

const GENERIC_ARTICLES = [
  "مادهٔ ۲۴ قانون کار — مزایای پایان کار و سنوات خدمت",
  "قانون عیدی و پاداش کارگران، مصوب ۱۳۷۰",
  "مادهٔ ۶۴ قانون کار — مرخصی استحقاقی سالانه",
  "مادهٔ ۵۹ قانون کار — فوق‌العادهٔ اضافه‌کاری",
  "مادهٔ ۳۷ قانون کار — موعد پرداخت مزد",
];

export function buildDocumentContent(input: DocContentInput): DocumentContent {
  const { docType, name, employer, yearsFa, salaryFa, contract, hasDetailed, claimsList, totalFa, hasClaims } = input;

  const employmentSummary = hasDetailed
    ? `به مدت حدود ${yearsFa} سال در واحد «${employer}» با قرارداد ${contract || "—"} مشغول به کار بوده‌ام و آخرین مزد ماهانهٔ اینجانب مبلغ ${salaryFa} تومان بوده است`
    : `از کارفرمای خود «${employer}» به دلیل عدم پرداخت مطالبات قانونی متحمل خسارت شده‌ام`;

  if (docType === DOC_TYPE.DISMISSAL) {
    const dismissalDate = input.dismissalDate?.trim() ? `در تاریخ ${input.dismissalDate}` : "اخیراً";
    return {
      recipientTitle: "اعتراض به اخراج و درخواست بازگشت به کار",
      recipientSub: "هیأت تشخیص ادارهٔ تعاون، کار و رفاه اجتماعی",
      plaintiffLabel: "خواهان (کارگر اخراجی)",
      defendantLabel: "خوانده (کارفرما)",
      subject: "اعتراض به اخراج غیرقانونی و درخواست بازگشت به کار",
      body:
        `ریاست محترم هیأت تشخیص ادارهٔ تعاون، کار و رفاه اجتماعی؛ احتراماً اینجانب ${name} ${employmentSummary}. اینجانب ${dismissalDate} بدون رعایت تشریفات قانونی مقرر در مادهٔ ۲۷ قانون کار (از جمله عدم اخذ نظر مثبت شورای اسلامی کار یا نمایندهٔ کارگران و عدم اعلام دلیل موجه) از سوی کارفرما اخراج شده‌ام. این اقدام، اخراج غیرموجه محسوب شده و مستند به مادهٔ ۱۶۵ قانون کار، در صورت احراز غیرموجه بودن اخراج، بازگشت به کار و پرداخت حق‌السعی از تاریخ اخراج مورد حکم قرار می‌گیرد. لذا رسیدگی و صدور رأی به شرح خواستهٔ ذیل مورد استدعاست.`,
      tableTitle: hasClaims ? "مطالبات مالی جانبی (در صورت عدم بازگشت به کار)" : "مطالبات مالی جانبی",
      articles: [
        "مادهٔ ۲۷ قانون کار — شرایط قانونی فسخ قرارداد کار از سوی کارفرما",
        "مادهٔ ۱۵۷ قانون کار — رسیدگی اختلاف در هیأت تشخیص",
        "مادهٔ ۱۵۹ قانون کار — مهلت ۱۵ روزهٔ اعتراض به رأی هیأت تشخیص",
        "مادهٔ ۱۶۵ قانون کار — بازگشت به کار یا پرداخت سنوات ۴۵ روزه در صورت اخراج غیرموجه",
      ],
      finalRequest:
        `با عنایت به مراتب فوق، صدور حکم به بازگشت به کار اینجانب و پرداخت حق‌السعی ایام تعلیق از تاریخ اخراج؛ و در صورت عدم امکان بازگشت به کار، الزام خوانده به پرداخت حق سنوات معادل ۴۵ روز مزد به ازای هر سال سابقه، موضوع تبصرهٔ مادهٔ ۱۶۵ قانون کار${hasClaims ? `، به‌انضمام مبلغ ${totalFa} بابت سایر مطالبات قانونی (${claimsList})` : ""}، از آن مرجع محترم مورد استدعاست.`,
      signatureLabel: "امضای خواهان",
    };
  }

  if (docType === DOC_TYPE.INSURANCE) {
    const period = input.insurancePeriod?.trim() ? `در بازهٔ ${input.insurancePeriod}` : "در طول دورهٔ اشتغال اینجانب";
    return {
      recipientTitle: "شکایت‌نامهٔ تأمین اجتماعی",
      recipientSub: "سازمان تأمین اجتماعی — شعبهٔ ذی‌ربط",
      plaintiffLabel: "شاکی (بیمه‌شده)",
      defendantLabel: "طرف شکایت (کارفرما)",
      subject: "پیگیری کسری بیمه و عدم واریز حق بیمه توسط کارفرما",
      body:
        `ریاست محترم شعبهٔ تأمین اجتماعی؛ احتراماً اینجانب ${name} ${employmentSummary}. کارفرمای مذکور علی‌رغم تکلیف مقرر در مادهٔ ۱۴۸ قانون کار مبنی بر بیمه‌نمودن کارگران نزد سازمان تأمین اجتماعی، ${period} نسبت به واریز کامل حق بیمهٔ اینجانب اقدام ننموده یا با کسری مواجه بوده است. این امر موجب اختلال در احتساب سوابق بیمه‌ای و محرومیت از مزایای قانونی (بازنشستگی، ازکارافتادگی و بیمهٔ بیکاری) اینجانب خواهد شد. لذا رسیدگی و صدور رأی به شرح خواستهٔ ذیل مورد استدعاست.`,
      tableTitle: hasClaims ? "مطالبات مزدی جانبی" : "مطالبات",
      articles: [
        "مادهٔ ۱۴۸ قانون کار — تکلیف کارفرما به بیمه‌نمودن کارگر نزد سازمان تأمین اجتماعی",
        "قانون تأمین اجتماعی و آیین‌نامه‌های اجرایی مربوط به کسر و پرداخت حق بیمه",
        "مادهٔ ۱۵۷ قانون کار — رسیدگی در هیأت تشخیص در صورت اختلاف با کارفرما",
      ],
      finalRequest:
        `با عنایت به مراتب فوق، الزام کارفرمای مذکور به احتساب و واریز حق بیمهٔ معوقهٔ دورهٔ اشتغال و اصلاح سوابق بیمه‌ای اینجانب نزد سازمان تأمین اجتماعی${hasClaims ? `، به‌انضمام مبلغ ${totalFa} بابت سایر مطالبات قانونی (${claimsList})` : ""}، مورد استدعاست.`,
      signatureLabel: "امضای شاکی",
    };
  }

  if (docType === DOC_TYPE.NOTICE) {
    const days = input.noticeDeadlineDays?.trim() || "۱۰";
    return {
      recipientTitle: "اظهارنامهٔ مطالباتی",
      recipientSub: `خطاب به: ${employer}`,
      plaintiffLabel: "اظهارکننده (کارگر)",
      defendantLabel: "مخاطب (کارفرما)",
      subject: "اخطار و مطالبهٔ رسمی حقوق و مزایای معوقه پیش از طرح شکایت در ادارهٔ کار",
      body:
        `جناب آقای/شرکت ${employer}؛ احتراماً به استحضار می‌رساند اینجانب ${name} ${employmentSummary}. علی‌رغم پیگیری‌های مکرر، مطالبات قانونی مشروحهٔ ذیل تاکنون پرداخت نشده است. بدین‌وسیله به استناد قانون کار، ظرف مهلت ${days} روز از تاریخ ابلاغ این اظهارنامه، نسبت به تسویهٔ کامل مبلغ مذکور اقدام فرمایید؛ در غیر این صورت، اینجانب ناگزیر از طرح دادخواست در هیأت تشخیص ادارهٔ تعاون، کار و رفاه اجتماعی و مطالبهٔ خسارت تأخیر تأدیه خواهم بود.`,
      tableTitle: "جدول مطالبات",
      articles: [...GENERIC_ARTICLES, "مادهٔ ۱۵۷ قانون کار — رسیدگی در هیأت تشخیص در صورت عدم نتیجه"],
      finalRequest:
        `بدین‌وسیله اخطار می‌شود ظرف مهلت ${days} روزهٔ فوق نسبت به پرداخت مبلغ ${totalFa} اقدام گردد؛ در غیر این صورت، موضوع از طریق مراجع قانونی (هیأت تشخیص ادارهٔ تعاون، کار و رفاه اجتماعی) پیگیری و مطالبهٔ خسارت تأخیر تأدیه نیز خواهد شد.`,
      signatureLabel: "امضای اظهارکننده",
    };
  }

  return {
    recipientTitle: "دادخواست مطالبهٔ حقوق",
    recipientSub: "ادارهٔ تعاون، کار و رفاه اجتماعی",
    plaintiffLabel: "خواهان (شاکی)",
    defendantLabel: "خوانده (طرف شکایت)",
    subject: `مطالبهٔ ${claimsList}`,
    body: hasDetailed
      ? `ریاست محترم ادارهٔ تعاون، کار و رفاه اجتماعی؛ احتراماً اینجانب ${name} ${employmentSummary}. متأسفانه کارفرما تا کنون از پرداخت حقوق و مزایای قانونی ذیل خودداری نموده است. لذا مستند به مواد قانون کار، رسیدگی و صدور رأی مبنی بر محکومیت خوانده به پرداخت مطالبات زیر مورد استدعاست.`
      : `ریاست محترم ادارهٔ تعاون، کار و رفاه اجتماعی؛ احتراماً اینجانب ${name} ${employmentSummary}. لذا مستند به قانون کار، رسیدگی و صدور رأی مبنی بر محکومیت خوانده به پرداخت مطالبات زیر مورد استدعاست.`,
    tableTitle: "جدول مطالبات",
    articles: [...GENERIC_ARTICLES, "مادهٔ ۱۵۷ قانون کار — رسیدگی در هیأت تشخیص"],
    finalRequest: `با عنایت به مراتب فوق، صدور حکم به محکومیت خوانده به پرداخت مجموع مبلغ ${totalFa} به انضمام خسارات و حقوق قانونی متعلقه، از آن مرجع محترم مورد استدعاست.`,
    signatureLabel: "امضای خواهان",
  };
}
